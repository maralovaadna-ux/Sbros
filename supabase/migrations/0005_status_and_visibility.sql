-- ---------- статус предложения (управляется вручную админом) ----------
create type public.offer_status as enum ('active', 'finished');

alter table public.offers
  add column status public.offer_status not null default 'active';

comment on column public.offers.status is 'Ручной статус для витрины: active — обычное, finished — показывается как "ЗАКОНЧЕН" (в т.ч. для фейковых прошедших СБРОСов ради соц. доказательства)';

-- ---------- ручной маркетинговый штамп "Продано X/Y" ----------
alter table public.offers
  add column manual_sold_count int;

comment on column public.offers.manual_sold_count is 'Вручную выставленное число для штампа "Продано X/Y" — не подменяет честный счётчик участников, показывается рядом';

